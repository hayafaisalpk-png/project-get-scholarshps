-- =============================================================================
-- 030_media_alt_text_or_decorative.sql
--
-- Alt-text coverage enforcement for the media library (Phase 5, increment 5).
--
-- THE PROBLEM
--
-- `media_assets.alt_text` is nullable and the editor told editors to "leave empty
-- only if the image is purely decorative". Nothing recorded WHETHER they were
-- looking at a decorative image or had simply forgotten, because the column
-- cannot tell those apart: both are `NULL`.
--
-- That makes enforcement impossible in principle, not merely unimplemented. You
-- cannot require a value on a column whose empty state is simultaneously correct
-- for a decorative image. So the distinction has to be stored.
--
-- WHAT CHANGES
--
--   is_decorative boolean not null default false
--
-- plus a CHECK that makes the two states mutually exclusive:
--
--   check (is_decorative or alt_text is not null)
--
-- An asset is therefore EITHER described OR explicitly decorative. "Neither" is
-- no longer representable, which is the whole point.
--
-- BACKFILL
--
-- Existing rows with no alt text are set `is_decorative = true`.
--
-- That is a claim this migration cannot verify — it is choosing the reading that
-- does not assert something untrue about content nobody has described yet. The
-- alternative, inventing alt text for every existing asset, would be fabricated
-- accessibility copy (`AGENTS.md` §2.7). The linked project holds only
-- development fixtures and no production assets, so the choice is reversible by
-- an editor who disagrees with it.
--
-- WHAT THIS DOES NOT DO
--
-- It does not make any image appear on the public site. No `<img>` or
-- `next/image` is rendered anywhere in the public routes today — the OG cards
-- are generated by `ImageResponse`, which does not use alt text. `alt_text` is
-- therefore correct and enforced in the library, and has **no effect on what a
-- visitor experiences yet**. The featured-image picker in Phase 4 is what will
-- make it matter, and this constraint is what will be standing behind it.
--
-- This migration is idempotent.
-- ---------------------------------------------------------------------------

alter table public.media_assets
  add column if not exists is_decorative boolean not null default false;

-- Backfill before adding the CHECK: the constraint would fail against the
-- existing rows, which is correct behaviour and useless as a migration strategy.
update public.media_assets
   set is_decorative = true
 where alt_text is null;

alter table public.media_assets
  drop constraint if exists media_assets_alt_or_decorative;

alter table public.media_assets
  add constraint media_assets_alt_or_decorative check (
    is_decorative or alt_text is not null
  );

comment on column public.media_assets.is_decorative is
  'True when the image carries no information (a rule, a flourish) and must be hidden from assistive technology. A decorative asset is allowed to have no alt text; nothing else is.';

-- -----------------------------------------------------------------------------
-- Self-check.
--
-- Two things must hold when this migration finishes: the column exists, and no
-- row is left in the state the CHECK forbids. The second is the one that matters
-- — a constraint added over data that already violates it fails the deployment
-- rather than the migration, and this must fail HERE with a readable message.
-- -----------------------------------------------------------------------------
do $$
declare
  offenders bigint;
begin
  if not exists (
    select 1 from information_schema.columns
     where table_schema = 'public'
       and table_name   = 'media_assets'
       and column_name  = 'is_decorative'
  ) then
    raise exception 'media_assets.is_decorative was not created';
  end if;

  select count(*) into offenders
    from public.media_assets
   where not is_decorative and alt_text is null;

  if offenders > 0 then
    raise exception '% media asset(s) have neither alt text nor a decorative flag', offenders;
  end if;
end;
$$;

notify pgrst, 'reload schema';