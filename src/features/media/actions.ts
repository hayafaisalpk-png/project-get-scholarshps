/**
 * Update alt text, caption, attribution, folder, public flag or decorative flag.
 *
 * Plain arguments rather than a `FormData` action, matching
 * `setArticleStatusAction`: the editor UI is a per-card panel driven from a
 * transition, not a submit-and-navigate form.
 *
 * ALT TEXT IS REQUIRED, EXCEPT WHEN DECLARED DECORATIVE.
 *
 * Alt text is the accessible name of the image on every page that uses it, and an
 * empty `alt` is the correct declaration only for an image that carries no
 * information. Those two cases were previously the same `NULL`, so the database
 * could require neither. `is_decorative` records which one it is, and the CHECK
 * `media_assets_alt_or_decorative` makes "neither" unrepresentable.
 *
 * An empty alt on a DECORATIVE asset is kept as `null` rather than an empty
 * string, because that is what the renderer needs to decide `alt=""` — an
 * explicit "skip me" — against a missing attribute, which a browser exposes as
 * the file name.
 */
export async function updateMediaAction(
  id: string,
  input: {
    altText: string
    caption: string
    attribution: string
    folder: string
    isPublic: boolean
    isDecorative: boolean
  },
): Promise<MediaActionResult> {
  await requirePermission('media.manage')

  if (!isUuid(id)) {
    return { ok: false, message: 'That asset could not be identified.' }
  }

  const parsed = mediaMetadataSchema.safeParse(input)

  if (!parsed.success) {
    return { ok: false, message: 'Check the highlighted fields.' }
  }

  // Refused here with a message an editor can act on, rather than at the
  // database as a bare constraint violation. The CHECK is still the backstop.
  if (!parsed.data.isDecorative && parsed.data.altText === '') {
    return {
      ok: false,
      message:
        'Describe the image, or mark it decorative if it carries no information.',
    }
  }

  const supabase = await createClient()

  const { data: asset, error: assetError } = await supabase
    .from('media_assets')
    .select('storage_path, public_url, is_public, mime_type')
    .eq('id', id)
    .maybeSingle()

  if (assetError || !asset) {
    return { ok: false, message: 'That asset could not be found.' }
  }

  let storagePath = asset.storage_path
  let publicUrl = asset.public_url
  const currentBucket = storagePath.split('/')[0] as Bucket | undefined
  const currentPath = storagePath.split('/').slice(1).join('/')
  const nextBucket = bucketFor(parsed.data.isPublic)

  if (
    (currentBucket !== 'public-media' && currentBucket !== 'private-media') ||
    !currentPath
  ) {
    return { ok: false, message: 'That asset has an invalid storage path.' }
  }

  if (currentBucket !== nextBucket) {
    const { data: file, error: downloadError } = await supabase.storage
      .from(currentBucket)
      .download(currentPath)

    if (downloadError || !file) {
      return { ok: false, message: 'The image could not be moved.' }
    }

    const { error: uploadError } = await supabase.storage
      .from(nextBucket)
      .upload(currentPath, file, {
        cacheControl: '31536000',
        contentType: asset.mime_type,
        upsert: false,
      })

    if (uploadError) {
      console.error('[media] visibility upload failed:', uploadError.message)
      return { ok: false, message: 'The image could not be moved.' }
    }

    const { error: removeError } = await supabase.storage
      .from(currentBucket)
      .remove([currentPath])

    if (removeError) {
      await supabase.storage.from(nextBucket).remove([currentPath])
      console.error('[media] visibility cleanup failed:', removeError.message)
      return { ok: false, message: 'The image could not be moved.' }
    }

    storagePath = `${nextBucket}/${currentPath}`
    publicUrl =
      nextBucket === 'public-media'
        ? supabase.storage.from(nextBucket).getPublicUrl(currentPath).data.publicUrl
        : null
  } else if (nextBucket === 'public-media') {
    publicUrl = supabase.storage
      .from(nextBucket)
      .getPublicUrl(currentPath).data.publicUrl
  }

  const { error } = await supabase
    .from('media_assets')
    .update({
      alt_text: parsed.data.altText === '' ? null : parsed.data.altText,
      is_decorative: parsed.data.isDecorative,
      caption: parsed.data.caption === '' ? null : parsed.data.caption,
      attribution:
        parsed.data.attribution === '' ? null : parsed.data.attribution,
      folder: parsed.data.folder,
      is_public: parsed.data.isPublic,
      storage_path: storagePath,
      public_url: publicUrl,
    })
    .eq('id', id)

  if (error) {
    console.error('[media] update failed:', error.message)

    if (error.code === '23514') {
      return {
        ok: false,
        message:
          'Describe the image, or mark it decorative if it carries no information.',
      }
    }
    return { ok: false, message: 'That change could not be saved.' }
  }

  revalidatePath('/admin/media')
  return { ok: true, message: 'Saved.' }
}

/** Cheap shape check so a malformed id cannot become a PostgREST filter value. */
function isUuid(value: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
    value,
  )
}

