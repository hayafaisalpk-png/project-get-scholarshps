/**
 * Media library Server Actions.
 *
 * Authorization runs before any validation or upload, so an unprivileged caller
 * never gets to push bytes. Row Level Security is the backstop: `media_assets`
 * requires `media.upload` to insert and `media.manage` to update or delete, and
 * the storage policies independently require the same permissions on
 * `storage.objects`.
 *
 * UPLOAD ORDER MATTERS
 *
 * The storage object is written FIRST and the database row SECOND, and the row is
 * only inserted once the upload succeeds. Doing it the other way round leaves
 * rows pointing at objects that do not exist, which surface as broken images on a
 * published page. If the row insert fails after a successful upload, the orphaned
 * object is removed in the same request rather than being left behind for someone
 * to find later.
 *
 * The id is generated by `crypto.randomUUID()` here so the storage path and the
 * database row can share it, rather than relying on insert-then-upload and
 * discovering a collision.
 */
export type MediaActionResult =
  | {
      ok: true
      message: string
      id?: string
      asset?: SelectableAsset
    }
  | { ok: false; message: string; fieldErrors?: Record<string, string> }

type Bucket = 'public-media' | 'private-media'

function bucketFor(isPublic: boolean): Bucket {
  return isPublic ? 'public-media' : 'private-media'
}

export async function uploadMediaAction(
  _prev: MediaActionResult | null,
  formData: FormData,
): Promise<MediaActionResult> {
  // Authorize FIRST. `requirePermission` throws on failure.
  await requirePermission('media.upload')

  const file = formData.get('file')

  if (!(file instanceof File) || file.size === 0) {
    return { ok: false, message: 'Choose a file to upload.' }
  }

  /*
   * The bytes are read here and checked by magic number. `file.type` and the
   * filename are both attacker-controlled and can be made to agree with each
   * other — an HTML document named `photo.png` and declared `image/png` passes
   * every field-level check. Reading the content is the only check that cannot be
   * spoofed, and it must happen before the object is written to the bucket rather
   * than afterwards.
   */
  const bytes = new Uint8Array(await file.arrayBuffer())

  const check = checkUploadFile({
    type: file.type,
    size: file.size,
    name: file.name,
    bytes,
  })
  if (!check.ok) return { ok: false, message: check.message }

  const parsed = mediaMetadataSchema.safeParse({
    altText: formData.get('altText'),
    caption: formData.get('caption'),
    attribution: formData.get('attribution'),
    folder: formData.get('folder'),
    isPublic: formData.get('isPublic') === 'on',
    isDecorative: formData.get('isDecorative') === 'on',
  })

  if (!parsed.success) {
    return {
      ok: false,
      message: 'Check the highlighted fields.',
      fieldErrors: parsed.error.issues.reduce<Record<string, string>>((acc, issue) => {
        const key = issue.path.join('.') || '_form'
        if (!(key in acc)) acc[key] = issue.message
        return acc
      }, {}),
    }
  }

  /*
   * An SVG is scriptable. Storing one in the public bucket is a deliberate act,
   * so it is not something a stray checkbox does by accident — the form warns
   * about it and the default stays private.
   */
  const wantsPublic = parsed.data.isPublic
  const isPublic = wantsPublic
  const bucket = bucketFor(isPublic)

  /*
   * Checked BEFORE the upload, not after.
   *
   * The `media_assets_alt_or_decorative` CHECK would reject the insert anyway,
   * but by then the bytes are already in the bucket and the cleanup path runs.
   * Refusing first means an upload that cannot be saved never happens.
   */
  if (!parsed.data.isDecorative && parsed.data.altText === '') {
    return {
      ok: false,
      message:
        'Describe the image, or mark it decorative if it carries no information.',
      fieldErrors: {
        altText: 'Describe the image, or mark it decorative.',
      },
    }
  }

  const id = crypto.randomUUID()
  const storagePath = buildStoragePath({
    id,
    mimeType: check.mimeType as AllowedMimeType,
    bucket,
    folder: parsed.data.folder,
  })
  const objectPath = storagePath.split('/').slice(1).join('/')

  const supabase = await createClient()

  const { error: uploadError } = await supabase.storage
    .from(bucket)
    .upload(objectPath, file, {
      cacheControl: '31536000',
      contentType: check.mimeType,
      upsert: false,
    })

  if (uploadError) {
    // Storage rejects unknown MIME types and oversized files itself. That error is
    // deliberately not surfaced verbatim: it names internal bucket configuration.
    console.error('[media] storage upload failed:', uploadError.message)
    return {
      ok: false,
      message: `That file could not be uploaded. Images must be under 5 MB and one of: ${ALLOWED_MIME_TYPES.join(', ')}.`,
    }
  }

  const { data: publicData } = supabase.storage
    .from(bucket)
    .getPublicUrl(objectPath)

  const publicUrl =
    bucket === 'public-media' ? (publicData?.publicUrl ?? null) : null

  // `uploaded_by = auth.uid()` is required by the media_insert_upload policy.
  const uploadedBy = await currentUserId(supabase)

  const { error: insertError } = await supabase
    .from('media_assets')
    .insert({
      id,
      storage_path: storagePath,
      public_url: publicUrl,
      is_public: isPublic,
      file_name: file.name.slice(0, 300),
      mime_type: check.mimeType,
      // `not null` with a `> 0` CHECK, so it must be written explicitly. Taken
      // from the browser's own File, which is only a hint — the bucket's real
      // limit is the one that actually enforces the bound.
      file_size: file.size,
      alt_text: parsed.data.altText === '' ? null : parsed.data.altText,
      is_decorative: parsed.data.isDecorative,
      caption: parsed.data.caption === '' ? null : parsed.data.caption,
      attribution: parsed.data.attribution === '' ? null : parsed.data.attribution,
      folder: parsed.data.folder,
      uploaded_by: uploadedBy,
      // Width and height are left null: they are not known client-side and are
      // not required by any schema constraint. A future image-probe can fill them.
    })

  if (insertError) {
    // The bytes are in the bucket but nothing points at them. Remove them now
    // rather than leaving an orphan.
    console.error('[media] row insert failed:', insertError.message)
    await supabase.storage.from(bucket).remove([objectPath])
    return {
      ok: false,
      message: 'The file was uploaded but could not be recorded. Nothing was saved.',
    }
  }

  revalidatePath('/admin/media')

  return {
    ok: true,
    id,
    asset: {
      id,
      fileName: file.name.slice(0, 300),
      altText: parsed.data.altText === '' ? null : parsed.data.altText,
      isDecorative: parsed.data.isDecorative,
      displayUrl: publicUrl,
    },
    message: check.scriptable
      ? `Uploaded to the PRIVATE bucket. "${file.name}" is an SVG, which can contain script — review it before making it public.`
      : `Uploaded to the ${bucket === 'public-media' ? 'public' : 'private'} bucket.`,
  }
}

/** The signed-in user id, for the `uploaded_by` column. */
async function currentUserId(
  supabase: Awaited<ReturnType<typeof createClient>>,
): Promise<string | null> {
  const { data } = await supabase.auth.getClaims()
  return data?.claims?.sub ?? null
}

