/**
 * Search the library from the picker.
 *
 * A separate action rather than importing `listSelectableAssets` into the client
 * component: `queries.ts` is `server-only`, and shipping the whole library to the
 * browser to filter there would defeat RLS — a user without `media.manage` would
 * receive asset rows they are not allowed to read.
 *
 * Permission is `media.manage` OR the ability to edit content, because the picker
 * is opened from the article and scholarship forms. `requireAnyPermission` runs
 * first, and the underlying SELECT policy still scopes which rows come back, so
 * this widens WHO MAY ASK, never WHAT THEY SEE.
 */
export async function searchSelectableAssets(
  q: string,
): Promise<
  | { ok: true; items: SelectableAsset[]; total: number }
  | { ok: false; message: string }
> {
  const { user } = await requireAnyPermission([
    'media.manage',
    'article.manage',
    'article.create',
    'scholarship.manage',
  ])

  void user

  const result = await listSelectableAssets({ q: q.slice(0, 120), page: 1 })

  if (!result.ok) {
    console.error('[media] picker search failed:', result.error.message)
    return { ok: false, message: 'The library could not be loaded.' }
  }

  return { ok: true, items: result.data.items, total: result.data.total }
}

