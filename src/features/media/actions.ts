/**
 * Archive rather than destroy.
 *
 * `media_assets.archived_at` is soft-delete, and RLS already hides archived rows
 * from everyone without `media.manage`. Archiving is the safe default because an
 * asset is referenced by `scholarships.image_id` and `articles.featured_image_id`:
 * deleting the file out from under a published record turns a live image into a
 * broken one, and those foreign keys are `on delete set null`, so the row would
 * silently lose its image instead of failing loudly.
 */
export async function archiveMediaAction(
  id: string,
): Promise<MediaActionResult> {
  await requirePermission('media.manage')

  if (!isUuid(id)) {
    return { ok: false, message: 'That asset could not be identified.' }
  }

  const supabase = await createClient()

  const { error } = await supabase
    .from('media_assets')
    .update({ archived_at: new Date().toISOString() })
    .eq('id', id)

  if (error) {
    console.error('[media] archive failed:', error.message)
    return { ok: false, message: 'That asset could not be archived.' }
  }

  revalidatePath('/admin/media')
  return { ok: true, message: 'Archived. The file itself is still in the bucket.' }
}
